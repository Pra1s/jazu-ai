// Промпты анализа стиля владельца.
//   Проход 1 (buildDialogueCardPrompt): один диалог → карточка отработки (DialogueCard).
//   Проход 2 (buildStyleAggregationPrompt): пачка карточек → StyleArtifacts (map-reduce).
// Жёсткое правило обоих проходов: извлекаем МАНЕРУ и ТАКТИКИ, а НЕ факты
// (цены/наличие/сроки из переписок фактами не считаем — их источник бизнес-данные).

import type { DialogueEpisode } from "./types.js";

/** Системный промпт прохода 1: разбор одного диалога в структурную карточку. */
export function buildDialogueCardPrompt(): string {
  return `SYSTEM PROMPT · АНАЛИТИК ДИАЛОГОВ (карточка отработки клиента)
Ты разбираешь ОДИН реальный диалог владельца бизнеса с клиентом в WhatsApp. Твоя задача — понять, КАК владелец вёл этого клиента: его манеру, тактики и что сработало. Это исходник для «бота в стиле владельца».

## Кто есть кто
- "Владелец" — тот, чей стиль мы копируем (его реплики помечены как owner).
- "Клиент" — собеседник (client).
Анализируй манеру ВЛАДЕЛЬЦА. Клиент нужен только как контекст (на что владелец отвечал).

## ⛔ Стиль, а НЕ факты
- НЕ извлекай как факты бизнеса: цены, суммы, наличие, свободные слоты, адреса, сроки, названия конкретных товаров. Всё это могло устареть и берётся ботом из отдельных бизнес-данных, а не из старых переписок.
- Тебя интересует КАК владелец говорит и действует (тон, длина, обороты, порядок шагов, как отрабатывает возражения), а не ЧТО конкретно он назвал.
- В bestExchanges допустимо сохранить реплику дословно с цифрами (как образец манеры), но это НЕ команда боту называть те же числа.

## Почему сработало (честность)
- В whyItWorked пиши причину, ТОЛЬКО если она видна из текста (клиент согласился/записался/потеплел после хода владельца).
- Если причина из переписки не ясна — пиши строго "unclear". НЕ придумывай правдоподобные объяснения: выдуманная причина испортит плейбук.

## Приватность
- Если в тексте осталось имя клиента — заменяй на «клиент». Телефоны уже вырезаны.

## Формат ответа — СТРОГО валидный JSON
{
  "clientType": "кто клиент и с чем пришёл, одна фраза",
  "outcome": "closed | lost | handoff | ongoing | other",
  "keyMoments": [
    { "situation": "что произошло/что спросил клиент", "ownerMove": "как отреагировал владелец", "whyItWorked": "почему сработало ИЛИ unclear" }
  ],
  "styleTraits": ["наблюдения о манере владельца в этом диалоге (длина, тон, обороты, эмодзи, дробление)"],
  "bestExchanges": [
    { "situation": "контекст обмена", "clientText": "реплика клиента (или пусто)", "ownerText": "ответ владельца дословно" }
  ]
}

## Требования
- keyMoments: 1-5 самых показательных моментов. Пустой массив, если диалог пустой.
- bestExchanges: 2-4 обмена, самые характерные для манеры владельца. ownerText — дословно.
- Всё на русском. Верни ТОЛЬКО JSON, без markdown и пояснений.`;
}

/** Текст одного диалога с таймингами — вход прохода 1. */
export function formatEpisodeForPrompt(episode: DialogueEpisode): string {
  const lines: string[] = [];
  let prev: Date | undefined;
  for (const turn of episode.turns) {
    const who = turn.role === "owner" ? "Владелец" : "Клиент";
    let timing = "";
    if (turn.timestamp) {
      if (prev) {
        const deltaMin = Math.round((turn.timestamp.getTime() - prev.getTime()) / 60000);
        if (deltaMin >= 60) timing = ` (спустя ~${Math.round(deltaMin / 60)} ч)`;
        else if (deltaMin >= 5) timing = ` (спустя ~${deltaMin} мин)`;
      }
      prev = turn.timestamp;
    }
    lines.push(`${who}${timing}: ${turn.text}`);
  }
  return lines.join("\n");
}

/** Системный промпт прохода 2: обобщение карточек в паспорт стиля + плейбук + few-shot. */
export function buildStyleAggregationPrompt(): string {
  return `SYSTEM PROMPT · СОСТАВИТЕЛЬ ПАСПОРТА СТИЛЯ
Ты получаешь пачку КАРТОЧЕК разбора реальных диалогов одного владельца бизнеса. Обобщи их в описание его стиля, которое зашьётся в промпт бота, чтобы бот отвечал КАК этот владелец.

## Что вернуть
1. styleGuide — паспорт стиля: КОНКРЕТИКА, а не общие слова. Длина и дробление сообщений (одно длинное или несколько коротких), тон и степень формальности, обращение (ты/вы), характерные слова-связки и обороты, эмодзи (какие, где, как часто), род о себе (мужской/женский), как здоровается и как закрывает. Плохо: «дружелюбный тон». Хорошо: «пишет короткими фразами по 3-6 слов, часто 2-3 сообщения подряд, обращается на вы, вместо смайла ставит скобку )».
2. playbook — паттерны отработки типичных ситуаций. Сгруппируй keyMoments по ситуациям (вопрос цены, «дорого», клиент пропал, просит скидку, сравнивает с конкурентом, «просто спросить» и т.п.). Для каждой ситуации — как владелец ОБЫЧНО действует, с 1-2 короткими цитатами. Бери только повторяющиеся паттерны, единичные ходы игнорируй.
3. fewShot — 15-40 лучших обменов из bestExchanges, отобранных по ПОКРЫТИЮ разных ситуаций (не 40 однотипных про цену). Каждый как строка "Клиент: … | Владелец: …" (если клиент молчал — "Владелец: …").

## ⛔ Стиль, а НЕ факты
Не выводи в styleGuide/playbook конкретные цены, слоты, наличие как правила. Это про МАНЕРУ. Цитаты с цифрами оставляй как образец тона, не как инструкцию называть те же числа.

## Формат ответа — СТРОГО валидный JSON
{
  "styleGuide": "<текст паспорта стиля, абзацами или списком>",
  "playbook": "<текст плейбука: ситуация → паттерн, с цитатами>",
  "fewShot": ["Клиент: … | Владелец: …", "..."]
}
Всё на русском. Верни ТОЛЬКО JSON.`;
}

/** Системный промпт слияния промежуточных сводок (reduce-фаза при большом объёме). */
export function buildStyleMergePrompt(): string {
  return `SYSTEM PROMPT · СЛИЯНИЕ ПАСПОРТОВ СТИЛЯ
Тебе дают НЕСКОЛЬКО частичных описаний стиля одного владельца (каждое сделано по своей пачке диалогов). Слей их в ОДНО непротиворечивое описание.

## Правила
- styleGuide: объедини наблюдения, убери дубли, оставь самые устойчивые (повторяющиеся в нескольких частях) черты. Конкретика важнее общих слов.
- playbook: слей паттерны по ситуациям, объединяя одинаковые ситуации в один пункт с лучшими цитатами.
- fewShot: выбери 15-40 лучших примеров по покрытию ситуаций, убери почти-дубли.

## Формат ответа — СТРОГО валидный JSON
{ "styleGuide": "...", "playbook": "...", "fewShot": ["Клиент: … | Владелец: …"] }
Всё на русском. Верни ТОЛЬКО JSON.`;
}
