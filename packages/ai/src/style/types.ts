// Единые типы фичи «бот в стиле владельца».
// Пайплайн: источник → DialogueEpisode[] → (rank) → DialogueCard[] → StyleArtifacts.
// Живут в @jazu/ai, потому что и парсер, и промпты, и оркестратор здесь.

/** Одна реплика диалога после парсинга источника (txt/JSON). */
export type DialogueTurn = {
  /** owner = владелец бизнеса (тот, чей стиль копируем), client = собеседник. */
  role: "owner" | "client";
  /** Текст реплики (уже с маской телефонов). */
  text: string;
  /** Время отправки, если источник его дал (для таймингов). */
  timestamp?: Date;
};

/**
 * Эпизод = один связный разговор с одним клиентом. Один файл/чат может дать
 * несколько эпизодов, если между сообщениями был большой разрыв (см. splitDays).
 */
export type DialogueEpisode = {
  /** Ярлык чата (имя контакта/файла) — уже замаскированный, для отладки/лейбла карточки. */
  chatLabel: string;
  /** Порядковый номер эпизода внутри исходного чата (0-based). */
  episodeIndex: number;
  /** Реплики в хронологическом порядке. */
  turns: DialogueTurn[];
  startedAt?: Date;
  endedAt?: Date;
};

/** Показательный обмен «клиент → владелец» из карточки (идёт в few-shot и RAG). */
export type DialogueExchange = {
  /** Ситуация/контекст обмена (например «возражение по цене»). */
  situation: string;
  /** Реплика клиента (может быть пустой, если владелец писал первым). */
  clientText: string;
  /** Ответ владельца — образец манеры (НЕ источник фактов). */
  ownerText: string;
};

/** Ключевой момент диалога: что произошло → как отработал владелец → почему сработало. */
export type DialogueKeyMoment = {
  situation: string;
  ownerMove: string;
  /** Почему сработало; "unclear", если из текста причина не видна (запрет выдумывать). */
  whyItWorked: string;
};

/** Результат анализа ОДНОГО диалога (проход 1). */
export type DialogueCard = {
  /** Тип клиента и с чем пришёл. */
  clientType: string;
  /** Исход: closed | lost | handoff | ongoing | other. */
  outcome: string;
  keyMoments: DialogueKeyMoment[];
  /** Замеченные стилевые черты владельца в этом диалоге. */
  styleTraits: string[];
  /** 2-4 показательных обмена дословно. */
  bestExchanges: DialogueExchange[];
};

/** Итог обобщения по всем карточкам (проход 2) — то, что зашивается в промпт. */
export type StyleArtifacts = {
  /** Паспорт стиля: как владелец пишет (длина, обороты, эмодзи, род, открытие/закрытие). */
  styleGuide: string;
  /** Плейбук: ситуация → доминирующий паттерн ответа (текст с цитатами). */
  playbook: string;
  /** Отобранные few-shot примеры (строки «Клиент: … / Владелец: …»). */
  fewShot: string[];
};
