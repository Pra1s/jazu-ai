// Воронка билдера урезана по фидбеку: минимум вопросов на входе. Только то, без чего
// бот не сориентируется. Всё остальное (название, часы, цены, FAQ, тон, передача,
// стоп-лиды, интеграции) добавляется позже в кабинете «доп данные о бизнесе» или
// дотачивается в тесте. servicesList — списком (не «главная услуга»). geography несёт
// и охват, и формат работы (выезд/точка). bookingFlow/anti-leads из воронки убраны:
// рантайм ведёт ОТ ПОТРЕБНОСТИ клиента, фиксированный «первый вопрос» не навязываем.
const requiredKeys: Array<keyof BusinessProfile> = [
  "niche",
  "servicesList",
  "geography",
  "leadGoal"
];

function isFilled(value: unknown): boolean {
  if (Array.isArray(value)) {
    return value.length > 0;
  }

  if (typeof value === "string") {
    return value.trim().length > 0;
  }

  return value !== undefined && value !== null;
}

export function mergeProfile(base: BusinessProfile, patch: Partial<BusinessProfile>): BusinessProfile {
  const merged: BusinessProfile = {
    ...base,
    ...patch,
    offerings: patch.offerings ?? base.offerings,
    languages: patch.languages ?? base.languages,
    faq: patch.faq ?? base.faq,
    examples: patch.examples ?? base.examples,
    notAllowed: patch.notAllowed ?? base.notAllowed,
    channels: patch.channels ?? base.channels,
    integrations: patch.integrations ?? base.integrations,
    emergencyCases: patch.emergencyCases ?? base.emergencyCases
  };

  return businessProfileSchema.parse(merged);
}

// К1: убрать из патча пустые/нулевые значения, чтобы они НЕ затирали уже собранные
// поля профиля при merge. LLM (особенно Gemini на free-tier) склонен возвращать
// полную схему с пустыми полями для того, что ещё не сказано. Пустое значение не
// несёт информации, но без чистки перетёрло бы базу: строковые поля — спредом
// (`...patch`) в mergeProfile, массивы вроде servicesList — без ??-защиты. Пустое
// поле трактуем как «нечего сказать», а не «сотри». Мутирует и возвращает тот же
// объект (вызывается на временном rawCompletionPatch). null/undefined — старая
// чистка N1 (Gemini слал businessName:null, схема такое не принимала).
export function stripEmptyPatchValues<T extends Record<string, unknown>>(patch: T): T {
  for (const key of Object.keys(patch)) {
    const v = patch[key];
    if (
      v === null ||
      v === undefined ||
      (typeof v === "string" && v.trim() === "") ||
      (Array.isArray(v) && v.length === 0)
    ) {
      delete patch[key];
    }
  }
  return patch;
}

export function inferMissingSections(profile: BusinessProfile): InterviewSection[] {
  const missing = interviewSections.filter((section) => {
    const value = profile[section.key];
    return !isFilled(value) && requiredKeys.includes(section.key);
  });

  return missing;
}

export function getNextQuestions(profile: BusinessProfile, max = 2): string[] {
  const missing = inferMissingSections(profile);
  return clampQuestions(
    missing.map((section) => section.followUp ? `${section.question} ${section.followUp}` : section.question),
    max
  );
}

export function buildInterviewChecklist(profile: BusinessProfile): string[] {
  return interviewSections.map((section) => {
    const value = profile[section.key];
    return `${section.label}: ${isFilled(value) ? "ok" : "нужно уточнить"}`;
  });
}

