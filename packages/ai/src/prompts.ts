export type PromptSection = { header: string; body: string };

// Разбор промпта на преамбулу (до первого "## ") + упорядоченные секции "## Заголовок" + тело.
export function parsePromptSections(prompt: string): { preamble: string; sections: PromptSection[] } {
  const lines = prompt.split("\n");
  const sections: PromptSection[] = [];
  const preamble: string[] = [];
  let cur: { header: string; body: string[] } | null = null;
  const flush = () => {
    if (cur) sections.push({ header: cur.header, body: cur.body.join("\n").replace(/^\n+|\n+$/g, "") });
  };
  for (const line of lines) {
    if (/^##\s+\S/.test(line)) {
      flush();
      cur = { header: line.trim(), body: [] };
    } else if (cur) {
      cur.body.push(line);
    } else {
      preamble.push(line);
    }
  }
  flush();
  return { preamble: preamble.join("\n").replace(/\n+$/g, ""), sections };
}

// Сборка промпта обратно из преамбулы и секций.
export function assemblePrompt(preamble: string, sections: PromptSection[]): string {
  const parts: string[] = [];
  if (preamble.trim()) parts.push(preamble.trim());
  for (const s of sections) parts.push(`${s.header}\n${s.body}`.trim());
  return parts.join("\n\n");
}

// Вживить тело в каноническую секцию: заменить, если есть; иначе вставить по каноническому порядку.
function upsertSection(
  sections: PromptSection[],
  headerKey: keyof typeof SECTION_NAMES,
  body: string
): PromptSection[] {
  const header = SECTION_NAMES[headerKey];
  const next = sections.slice();
  const idx = next.findIndex((s) => s.header === header);
  if (idx >= 0) {
    next[idx] = { header, body };
    return next;
  }
  // Секции нет — найти место по каноническому порядку (перед первой секцией, что идёт позже).
  const order = CANONICAL_SECTION_ORDER.indexOf(headerKey);
  const headerToKey = new Map<string, keyof typeof SECTION_NAMES>();
  for (const k of Object.keys(SECTION_NAMES) as (keyof typeof SECTION_NAMES)[]) headerToKey.set(SECTION_NAMES[k], k);
  let insertAt = next.length;
  for (const [i, sec] of next.entries()) {
    const k = headerToKey.get(sec.header);
    const o = k ? CANONICAL_SECTION_ORDER.indexOf(k) : -1;
    if (o !== -1 && o > order) { insertAt = i; break; }
  }
  next.splice(insertAt, 0, { header, body });
  return next;
}

// Обезвреживает markdown-заголовки ВНУТРИ тела секции. Владелец мог вставить строку
// «## ...» (или «### ...») в поле формы, и при следующем разборе она стала бы ФАНТОМНОЙ
// секцией → структура поехала бы. Заголовок секции задаёт только КОД, тело не должно
// содержать своих «#»-заголовков, поэтому снимаем ведущие '#'.
export function sanitizeSectionBody(body: string): string {
  return body
    .split("\n")
    .map((line) => line.replace(/^[ \t]*#{1,6}[ \t]+/, ""))
    .join("\n");
}

// Применить патчи секций (ключи = канонические заголовки) к промпту.
// Неканонические/пустые ключи ОТБРАСЫВАЮТСЯ — LLM не может создать выдуманную секцию.
// Тело каждого патча проходит sanitizeSectionBody (анти-фантомные секции из ввода владельца).
// Возвращает обновлённый промпт + список реально применённых заголовков.
export function applySectionPatches(
  prompt: string,
  patches: Record<string, string>
): { newPrompt: string; sectionsApplied: string[] } {
  const headerToKey = new Map<string, keyof typeof SECTION_NAMES>();
  for (const k of Object.keys(SECTION_NAMES) as (keyof typeof SECTION_NAMES)[]) headerToKey.set(SECTION_NAMES[k], k);
  const { preamble } = parsePromptSections(prompt);
  let { sections } = parsePromptSections(prompt);
  const applied: string[] = [];
  for (const [rawHeader, body] of Object.entries(patches)) {
    const key = headerToKey.get((rawHeader || "").trim());
    if (!key || !body || !body.trim()) continue; // не канон или пусто → игнор (анти-выдумка секций)
    sections = upsertSection(sections, key, sanitizeSectionBody(body.trim()));
    applied.push(SECTION_NAMES[key]);
  }
  return { newPrompt: assemblePrompt(preamble, sections), sectionsApplied: applied };
}

// Развязка роли/механики (§2A): carcass выводится в коде, остаётся перезаписываемым.
// Билдер отдаёт carcass только при override (иначе null), код подставляет дефолт роли.
