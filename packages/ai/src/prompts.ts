// Безопасный фоллбэк: для null-модели берём нейтральный пул, иначе пул роли.
export function getFallback(model: BotModel | null): string {
  return model ? pick(RUNTIME_FALLBACK[model] ?? DEFAULT_FALLBACKS) : pick(DEFAULT_FALLBACKS);
}

// Лёгкая валидация полноты промпта (§4). Не бросает: возвращает список notes
// для наблюдаемости. Пусто = ок.
export function assertPromptShape(businessPrompt: string, model: BotModel | null): string[] {
  const notes: string[] = [];
  for (const key of ["about", "task", "start"] as const) {
    if (!businessPrompt.includes(SECTION_NAMES[key])) {
      notes.push(`missing_section:${SECTION_NAMES[key]}`);
    }
  }
  if (!model) notes.push("missing_botModel");
  return notes;
}

export function summarizeLead(profile: BusinessProfile, message: string, extra: Record<string, unknown> = {}): string {
  const parts = [
    `Новый лид: ${profile.businessName || "без названия"}`,
    profile.niche ? `ниша: ${profile.niche}` : undefined,
    profile.targetAudience ? `аудитория: ${profile.targetAudience}` : undefined,
    profile.geography ? `география: ${profile.geography}` : undefined,
    `сообщение: ${message}`,
    ...Object.entries(extra).map(([key, value]) => `${key}: ${String(value)}`)
  ].filter(Boolean);

  return parts.join(", ");
}
