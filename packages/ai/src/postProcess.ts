//
// Зачем код, а не только промпт: модель устойчиво биасована на длинное тире (маркер ИИ),
// JSON-режим биас усиливает, одна негативная инструкция его не добивает на тысячах генераций.
// Поэтому чистим механически на выходе. ТОН (живость) санитайзером НЕ лечим — это работа
// few-shot в промпте (R6). Здесь только безопасные механические нормализации, не меняющие смысл.

/**
 * Убирает длинное/среднее тире из текста.
 *
 * ВАЖЕН ПОРЯДОК: числовые диапазоны нормализуем ПЕРВЫМИ (10–12 -> 10-12, СМЫСЛ диапазона
 * сохраняем дефисом), иначе правило "тире-пауза" перезапишет их в запятую и сломает диапазон
 * ("10–12" стало бы "10, 12").
 *
 * Что делаем:
 *   1) тесные числовые диапазоны (любые пробелы вокруг тире) -> дефис;
 *   2) тире-пауза с ПРОБЕЛАМИ по обе стороны -> запятая (это "человеческая" замена);
 *   3) двойной дефис "--" в роли тире-паузы -> запятая.
 *
 * Что НЕ трогаем (намеренно, чтобы не навредить):
 *   - закрытое тире без пробелов между буквами ("да—нет") — редкий случай, замена выглядела бы хуже;
 *   - тире в начале строки без пробела слева (возможный маркер списка);
 *   - минус U+2212 и обычный дефис-минус "-".
 *
 * Примеры:
 *   "Записать вас — на какое время?"   -> "Записать вас, на какое время?"
 *   "оценка 25 000 — 40 000"            -> "оценка 25 000-40 000"   (диапазон, НЕ запятая)
 *   "работаем 9:00–18:00"               -> "работаем 9:00-18:00"
 *   "это удобно -- я запишу"            -> "это удобно, я запишу"
 */
export function stripDashes(text: string): string {
  if (!text) return text;
  return text
    // 1) числовые диапазоны: 10–12 / 10 – 12 / 9:00–18:00 -> дефис (диапазон сохраняем)
    .replace(/(\d)\s*[—–]\s*(\d)/g, "$1-$2")
    // 2) тире-пауза с пробелами по обе стороны -> запятая
    .replace(/ +[—–] +/g, ", ")
    // 3) двойной дефис как тире-пауза -> запятая
    .replace(/ +-- +/g, ", ");
}

/**
 * Лёгкая косметика пробелов ПОСЛЕ замен: схлопнуть кратные горизонтальные пробелы,
 * убрать пробел перед знаком препинания, срезать хвостовые пробелы перед переводом строки.
 * Безопасно, смысл не меняет. Переводы строк (\n) намеренно сохраняем.
 */
export function tidyWhitespace(text: string): string {
  if (!text) return text;
  return text
    .replace(/[ \t]{2,}/g, " ")          // кратные пробелы -> один
    .replace(/[ \t]+([,.!?;:])/g, "$1")  // пробел перед пунктуацией -> убрать
    .replace(/[ \t]+\n/g, "\n")          // хвостовые пробелы перед \n
    .trim();
}

/**
 * Единая точка пост-обработки исходящего текста ДЛЯ ПОЛЬЗОВАТЕЛЯ.
 * Композиция stripDashes -> tidyWhitespace (порядок важен: сначала замены, потом косметика).
 *
 * Применять к: reply (Runtime), assistantText (Builder / Correction / Enrichment).
 * НЕ применять к: promptDraft и любым служебным/логовым полям.
 *
 * Пустая строка (спам/офф-топик у Runtime) проходит без изменений.
 */
export function postProcessUserText(text: string): string {
  return tidyWhitespace(stripDashes(text));
}
